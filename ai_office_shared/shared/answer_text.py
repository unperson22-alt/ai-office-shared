"""
ai_office_shared.shared.answer_text — достать ОТВЕТ из блоков модели.

ПРОБЛЕМА (инцидент 2026-08-15, «Крисс отвечает ненатурально»):
    Все боты с веб-поиском собирают ответ так:

        " ".join(b.text for b in r.content if hasattr(b, "text"))

    Пока модель не ходит в поиск, блок один и всё в порядке. Но со
    server-side web_search ответ состоит из НЕСКОЛЬКИХ блоков: сначала текст
    «сейчас поищу актуальные данные», потом сам вызов поиска и его результат,
    потом настоящий ответ. Склейка всех текстовых блоков даёт заикание:

        «Хороший вопрос — и здесь уже не про алгоритмы, а про психологию.
         Давай по-честному. Окей, данные есть. Погнали — это уже не про
         алгоритмы, это про то как зацепить людей...»

    Человек читает это как сбой — фраза начинается дважды. Строительные леса
    («сейчас поищу») предназначались не читателю, а самой модели.

РЕШЕНИЕ:
    Если в ответе были инструментальные блоки — берём текст ПОСЛЕ последнего
    из них. Всё до поиска — рассуждение по дороге, а не ответ.

    Если после инструмента модель ничего не сказала, отдаём что есть: пустой
    ответ хуже неаккуратного.
"""

from __future__ import annotations


def _is_tool_block(block) -> bool:
    t = str(getattr(block, "type", "") or "")
    return t.endswith("tool_use") or t.endswith("tool_result")


def extract_answer_text(content_blocks, *, sep: str = " ") -> str:
    """
    Текст ответа модели: только то, что сказано ПОСЛЕ последнего инструмента.

    Работает и когда инструментов не было — тогда это обычная склейка блоков,
    то есть прежнее поведение.
    """
    blocks = list(content_blocks or [])
    last_tool = -1
    for i, b in enumerate(blocks):
        if _is_tool_block(b):
            last_tool = i

    def _texts(seq):
        return [b.text for b in seq if getattr(b, "text", None)]

    tail = _texts(blocks[last_tool + 1:]) if last_tool >= 0 else _texts(blocks)
    if not tail:
        # После инструмента модель ничего не написала — лучше отдать
        # предисловие, чем пустоту: пустой ответ пользователь видит как
        # «бот сломался», а предисловие хотя бы что-то значит.
        tail = _texts(blocks)
    return sep.join(tail).strip()
