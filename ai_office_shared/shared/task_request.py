"""
ai_office_shared.shared.task_request — что считается заявкой на `POST /task`.

ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ МОДУЛЕМ, А НЕ ДВУМЯ СТРОЧКАМИ В КАЖДОМ ОБРАБОТЧИКЕ

02.09.2026 сессия Клода дважды попросила Силли задеплоить kriss-bot и дважды
получила `{"status": "done"}` с текстом её приветствия — «Привет! Я — Силли,
технический мозг AI-офиса». Деплой не произошёл. Полчаса ушло на разбор
«почему Силли не исполняет команду», в Notion уехала запись о дефекте офиса, а
в отчёт владельцу — вывод, что ops-канал сломан.

Сломан был не канал. Заявка ушла полем `task`, а обработчик берёт работу из
`message`:

    text = data.get("message", "")

Пустая строка дошла до LLM, та честно ответила на пустой вопрос — приветствием,
— и обработчик так же честно отрапортовал `done`. Каждое звено сработало по
своему контракту; неправильным был только СОСТАВ контракта: «нет работы» не
считалось ошибкой.

Три следствия, и все три — не про опечатку в одном вызове:

1. ОТСУТСТВИЕ РАБОТЫ РАПОРТОВАЛОСЬ КАК ВЫПОЛНЕННАЯ РАБОТА. Это форма урока
   #93: улику об успехе поставил тот, кому не на чем было исполниться. Вызывающий
   не может отличить «сделал» от «делать было нечего» — ни по статусу, ни по
   телу ответа.
2. ПРОВАЛ НАЗВАЛ НЕ ТОГО, КТО УПАЛ (инвариант 8 в CLAUDE.md). Виновным оказалась
   дальняя сторона, потому что она единственная что-то сказала, а сказала она
   не про заявку.
3. ПРАВИЛО РАЗЪЕХАЛОСЬ ПО ОФИСУ. kriss-bot пустую заявку отвергал, но ответом
   «empty message» — не называя ни нужного поля, ни того, что пришло вместо
   него. `worker.py` (то есть ВСЕ боты отдела разработки) и Силли принимали её
   молча. Один и тот же вопрос решался в трёх местах тремя способами.

Поэтому здесь одна функция, а не проверка на месте: правило про состав заявки
обязано быть одно, и текст отказа обязан называть поле. Отказ, который не
говорит «работа берётся из message, а пришло task», экономит вызывающему ровно
ничего — он всё так же не знает, что чинить.
"""

from __future__ import annotations

# Как поле называют те, кто пишет вызов по памяти или по аналогии с другим API.
# Список не для угадывания — принимается ТОЛЬКО `message`. Он для того, чтобы
# отказ мог сказать «ты прислал task» вместо «пусто».
_NEAR_MISSES = ("task", "text", "prompt", "query", "content", "body", "msg",
                "input", "request", "command")

TEXT_FIELD = "message"


class EmptyTask(ValueError):
    """
    В теле `POST /task` нет работы.

    Несёт готовый текст для вызывающего: обработчику остаётся отдать его с 400,
    а не сочинять формулировку заново в каждом сервисе.
    """

    def __init__(self, detail: str):
        super().__init__(detail)
        self.detail = detail


def task_text(data, *, field: str = TEXT_FIELD) -> str:
    """
    Текст заявки из тела запроса. Пусто — это EmptyTask, а не пустая строка.

    Возврат пустой строки был бы худшим из возможных ответов: он выглядит как
    валидная заявка и уезжает в LLM, которая на пустой вопрос отвечает
    приветствием. Молчаливое «ничего» обязано стать громким «нечего делать».
    """
    if not isinstance(data, dict):
        raise EmptyTask(
            f"тело запроса должно быть JSON-объектом с полем {field!r}; "
            f"пришло {type(data).__name__}")

    value = data.get(field)
    text = value.strip() if isinstance(value, str) else ""
    if text:
        return text

    raise EmptyTask(_explain(data, field))


def _explain(data: dict, field: str) -> str:
    """
    Почему заявка пустая — словами, которые называют поле.

    Отдельная функция затем, что её проверяют тестом: формулировка здесь —
    рабочая часть отказа, а не оформление. Отказ без имени поля возвращает
    вызывающего ровно туда, откуда он пришёл.
    """
    if field in data:
        got = data[field]
        if isinstance(got, str):
            return (f"поле {field!r} пустое — в заявке нет работы. "
                    f"Текст задачи кладётся в {field!r}.")
        return (f"поле {field!r} должно быть строкой, пришло "
                f"{type(got).__name__}. Текст задачи кладётся в {field!r}.")

    # Самое ценное, что тут можно сказать: под каким именем работа ПРИШЛА.
    misplaced = [k for k in _NEAR_MISSES
                 if isinstance(data.get(k), str) and data[k].strip()]
    keys = ", ".join(sorted(map(str, data))) or "(тело пустое)"
    if misplaced:
        return (f"работа берётся из поля {field!r}, а текст пришёл в "
                f"{', '.join(repr(k) for k in misplaced)}. Переименуй поле — "
                f"задача не выполнялась. Полученные поля: {keys}.")
    return (f"в теле нет поля {field!r} — задача не выполнялась. "
            f"Полученные поля: {keys}.")
