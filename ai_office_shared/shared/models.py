"""
ai_office_shared.shared.models
Единый источник правды по id моделей Anthropic для всех ботов офиса.

Использование:
    from ai_office_shared.shared.models import MODEL_SONNET, MODEL_HAIKU

    r = await client.messages.create(model=MODEL_SONNET, ...)

Каждую константу можно переопределить через переменную окружения с тем же именем
(например MODEL_SONNET=claude-sonnet-4-7), чтобы менять модель без правки кода.
"""
import os

# Основная модель ботов (диалог, синтез).
MODEL_SONNET = os.getenv("MODEL_SONNET", "claude-sonnet-4-6")

# Лёгкая/быстрая модель (роутинг, enhance, extract).
MODEL_HAIKU = os.getenv("MODEL_HAIKU", "claude-haiku-4-5-20251001")

# Тяжёлая модель для сложных рассуждений.
MODEL_OPUS = os.getenv("MODEL_OPUS", "claude-opus-4-8")


# ── Где в оркестрации какая модель ────────────────────────────────────────────
# ЗАЧЕМ ЭТО НЕ «ВЕЗДЕ САМАЯ МОЩНАЯ»:
#     Соблазн включить Opus на всю цепочку понятен, но он лечит не ту болезнь.
#     Отказы офиса за последние недели — не про качество рассуждений: у Силли
#     не было действия записать переменную, у Милли реплика молча
#     выбрасывалась, `/task` не нёс отправителя. Ни один Opus этого не
#     исправил бы: не хватало инструментов, полей и логов, а не интеллекта.
#     Зато Opus на каждом шаге даёт кратный счёт и заметную задержку в шагах,
#     где решение либо очевидно, либо детерминировано.
#
# ПРАВИЛО:
#     Тяжёлая модель — там, где ошибка дорога и необратима: разбиение задачи на
#     план и финальное решение «принято/на доработку». Исполнение — Sonnet.
#     Механика (роутинг, классификация, извлечение полей) — Haiku. Проверка,
#     которую можно выразить гейтом, вообще не должна ходить в модель.

STAGE_PLAN = "plan"            # декомпозиция задачи, критерии приёмки
STAGE_EXECUTE = "execute"      # бот делает работу по своему направлению
STAGE_ROUTE = "route"          # роутинг/классификация/извлечение полей
STAGE_REVIEW = "review"        # финальный вердикт по собранным уликам

_STAGE_MODELS = {
    STAGE_PLAN: MODEL_OPUS,
    STAGE_EXECUTE: MODEL_SONNET,
    STAGE_ROUTE: MODEL_HAIKU,
    STAGE_REVIEW: MODEL_OPUS,
}


def model_for_stage(stage: str) -> str:
    """
    Модель для этапа оркестрации. Неизвестный этап → Sonnet: безопасная
    середина, а не самая дорогая модель по умолчанию.
    """
    return _STAGE_MODELS.get(stage, MODEL_SONNET)
