"""
ai_office_shared.shared.phantom — детектор фантомных «отписок».

ПРОБЛЕМА:
    Маленькая локальная модель (Ollama gemma3:4b) и старые fallback-пути иногда
    выдают офф-персонажную заглушку вида «Сейчас технические работы — скоро
    вернусь, обычно это занимает несколько минут» или «я временно недоступен,
    попробуй позже». Такой текст уходит в офис-группу как «ответ»: со стороны
    выглядит, будто бот бредит и врёт про техработы, хотя сервисы живы.

РЕШЕНИЕ:
    Единая точка правды. Любой бот перед публикацией ответа спрашивает
    `looks_like_phantom(text)`. True — это не ответ, а заглушка: не постим, а
    падаем на нормальный путь (Anthropic / route_miss).

    Правило офиса «бот НИКОГДА не говорит, что идут техработы или что он
    недоступен» здесь превращается из промпт-костыля в исполняемый код.

ПОЧЕМУ ДВА КЛАССА МАРКЕРОВ:
    Первая версия резала любой короткий текст со словами «технические работы» —
    и вместе с заглушкой съедала бы осмысленный отчёт вроде «на Railway были
    техработы, два сервиса передеплоились, health у всех 200». Силли пишет такие
    по нескольку раз в день. Поэтому:

      • СИЛЬНЫЙ маркер — бот говорит о СВОЕЙ недоступности («скоро вернусь»,
        «временно недоступен», «попробуй позже»). Этого достаточно.
      • СЛАБЫЙ маркер — просто тема («технические работы», «ведутся работы»).
        Сам по себе не улика: гасим только если текст очень короткий, то есть
        кроме этой фразы в нём ничего и нет.

    Ошибаться безопаснее в сторону «пропустить заглушку», чем «съесть живой
    ответ»: непропущенная заглушка — косметика, съеденный ответ — потеря работы.
"""

from __future__ import annotations

import re

# Бот говорит о собственной недоступности. Достаточно сам по себе.
_STRONG_PATTERNS: tuple[re.Pattern, ...] = tuple(
    re.compile(p, re.IGNORECASE) for p in (
        r"скоро\s+верн\w+",                     # скоро вернусь / вернёмся
        r"временно\s+недоступ\w+",              # временно недоступен
        r"сейчас\s+недоступ\w+",                # сейчас недоступна
        r"\bя\s+недоступ\w+",                   # я недоступен
        r"попробуй\w*\s+(?:позже|попозже|чуть\s+позже|через\s+нескольк\w*\s+минут)",
        r"under\s+maintenance",
        r"try\s+again\s+later",
        r"temporarily\s+unavailable",
    )
)

# Только тема. Улика лишь в очень коротком тексте, где больше ничего нет.
_WEAK_PATTERNS: tuple[re.Pattern, ...] = tuple(
    re.compile(p, re.IGNORECASE) for p in (
        r"техническ\w*\s+работ\w*",             # технические работы
        r"вед[её]тся\w*\s+работ\w*",            # ведутся работы
        r"занимает\s+нескольк\w*\s+минут",      # обычно это занимает несколько минут
    )
)

# Заглушки короткие. Длинный ответ, где тема упомянута по делу, не трогаем.
MAX_PHANTOM_LEN = 320
# Порог для слабых маркеров: короче — значит кроме отписки там ничего нет.
MAX_WEAK_ONLY_LEN = 140


def looks_like_phantom(text: str | None) -> bool:
    """
    True, если текст выглядит как офф-персонажная заглушка «идут техработы /
    я недоступен / попробуй позже», а не как осмысленный ответ.

    Консервативен намеренно: сильный маркер срабатывает в тексте до
    MAX_PHANTOM_LEN символов, слабый — только до MAX_WEAK_ONLY_LEN.
    """
    if not text:
        return False
    t = text.strip()
    if not t or len(t) > MAX_PHANTOM_LEN:
        return False
    if any(p.search(t) for p in _STRONG_PATTERNS):
        return True
    if len(t) <= MAX_WEAK_ONLY_LEN and any(p.search(t) for p in _WEAK_PATTERNS):
        return True
    return False
