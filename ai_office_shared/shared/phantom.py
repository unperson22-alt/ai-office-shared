"""
ai_office_shared.shared.phantom — детектор фантомных «отписок».

Проблема: маленькая локальная модель (Ollama gemma3:4b) и старые fallback-пути
иногда выдают офф-персонажные заглушки вида «Сейчас технические работы — скоро
вернусь, обычно это занимает несколько минут» / «я временно недоступен, попробуй
позже». Такой текст попадает в офис-группу как «ответ» — пользователь видит, будто
бот «бредит» и врёт про техработы, хотя сервисы живы.

Единая точка правды: любой бот/шаред-код перед публикацией ответа пользователю может
спросить `looks_like_phantom(text)`. Если True — это не ответ, а заглушка: не постим,
а падаем на нормальный путь (Anthropic / route_miss).

Правило офиса (CLAUDE — СТАРТ): бот НИКОГДА не говорит, что идут техработы или что он
недоступен. Этот модуль — исполняемая версия того правила.
"""

from __future__ import annotations

import re

# Каждый паттерн — признак «отписки про недоступность/техработы».
# Сознательно узкие формулировки, чтобы не зацепить осмысленный ответ, где слово
# просто упомянуто по теме.
_PHANTOM_PATTERNS: tuple[re.Pattern, ...] = tuple(
    re.compile(p, re.IGNORECASE) for p in (
        r"техническ\w*\s+работ\w*",          # технические работы
        r"вед[её]тся\w*\s+работ\w*",           # ведутся работы
        r"скоро\s+верн\w+",                    # скоро вернусь / вернёмся
        r"занимает\s+нескольк\w*\s+минут",     # обычно это занимает несколько минут
        r"временно\s+недоступ\w+",             # временно недоступен
        r"сейчас\s+недоступ\w+",               # сейчас недоступна
        r"я\s+недоступ\w+",                    # я недоступен
        r"попробуй\w*\s+(?:позже|попозже|чуть\s+позже|через\s+нескольк\w*\s+минут)",
        r"under\s+maintenance",
        r"try\s+again\s+later",
    )
)

# Заглушки короткие. Настоящий ответ, где тема реально про техработы, обычно длиннее
# и содержательнее — его не режем.
_MAX_PHANTOM_LEN = 320


def looks_like_phantom(text: str | None) -> bool:
    """
    True, если текст выглядит как офф-персонажная заглушка «идут техработы / я
    недоступен / попробуй позже», а не как осмысленный ответ.

    Консервативно: срабатывает только на КОРОТКОМ тексте (<= 320 симв.), в котором
    есть характерный оборот про недоступность. Длинные содержательные ответы,
    упоминающие техработы по делу, не трогаем.
    """
    if not text:
        return False
    t = text.strip()
    if not t or len(t) > _MAX_PHANTOM_LEN:
        return False
    return any(p.search(t) for p in _PHANTOM_PATTERNS)
