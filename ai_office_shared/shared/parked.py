"""Сервис, который человек остановил, — не упавший сервис.

08.10.2026 Влад остановил торговый отдел: трейдер и Тилли стоили денег при
нулевой окупаемости. Через шесть минут watchdog поднял трейдера обратно
(/health молчит → редеплой), а 10.10 аудит Силли поднял Тилли: статус
REMOVED он читал как «деплой упал» и чинил. Остальные остановленные
боты ушли бы в сквозной обход отделов задачами «Упал сервис» на доске.

Ни один из реаниматоров не врал: сервис действительно не отвечал. Ошибка
была в том, что «не отвечает» и «упал» считались одним и тем же. Railway
различает их сам, поэтому отдельный список «на паузе» не заводим — его
пришлось бы держать в синхроне руками, и первым же забытым пунктом он бы
снова поднял остановленное:

- `REMOVED` у ПОСЛЕДНЕГО деплоя — активного деплоя нет совсем: его убрали
  (deploymentRemove / Remove в дашборде), упавший сервис так не выглядит;
- `SUCCESS` + `deploymentStopped` — собранный и здоровый деплой остановили
  (deploymentStop / Stop).

Один `deploymentStopped` уликой не является: Railway ставит его каждой
упавшей сборке (на 11.10.2026 — у всех 30 FAILED в офисе). Поэтому FAILED и
CRASHED — всегда падение, даже с этим флагом: пропустить настоящую поломку
дороже, чем лишний раз поднять остановленное. Гасить сервис надёжнее через
Remove — Stop после рестарта Railway может показать CRASHED.

Чтобы вернуть сервис под присмотр, достаточно Redeploy: у нового деплоя
нет ни того, ни другого признака.
"""

DEPLOY_STATE_QUERY = (
    "query($sid:String!){deployments(first:1,input:{serviceId:$sid})"
    "{edges{node{status deploymentStopped}}}}"
)


def deploy_state(data: dict) -> tuple[str, bool]:
    """Ответ DEPLOY_STATE_QUERY → (статус последнего деплоя, остановлен_человеком).

    Деплоев нет совсем → ("NO_DEPLOY", False): это кроны и не настроенные
    сервисы, остановленным их не называем.
    """
    edges = ((data or {}).get("data") or {}).get("deployments", {}).get("edges") or []
    if not edges:
        return "NO_DEPLOY", False
    node = edges[0].get("node") or {}
    status = node.get("status") or "UNKNOWN"
    stopped = node.get("deploymentStopped") is True
    return status, status == "REMOVED" or (status == "SUCCESS" and stopped)
